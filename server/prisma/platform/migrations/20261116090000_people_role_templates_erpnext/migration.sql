-- The People role templates, to the owner's decisions of 8 Nov 2026 and ERPNext HRMS's stock roles
-- (permissionCatalog.ts; the PR carries the mapping table).
--
--   HR Manager  gains Policies, Privacy (privacy requests) and Private Cases (confidential cases), and, as
--               ERPNext's HR Manager has, attendance records and shifts. It approves leave, as before.
--   HR User     never approves leave (it did not before either); gains what ERPNext's HR User has in People
--               and Attendance, additively: org structure, leave types, attendance records, shifts,
--               recruitment, performance, learning, the help desk and reading expenses.
--   Viewer      read-only employee records without confidential or HR-only files, full identifiers,
--               privacy work or confidential cases. Payroll stays out, as 20261107100100_viewer_without_payroll
--               left it (every payslip, report and full PAN), so the old Viewer template here has no Payroll row.
--   Auditor     gains read-only People: the employee list with joining and leaving dates. No documents, no
--               identifiers.
--
-- Two new grants split what one grant opened: HR-only documents (HR_ONLY files, which Documents VIEW alone
-- opened company-wide) and Full identifiers (showing a full PAN, UAN, bank or passport number, which
-- Statutory Details VIEW alone allowed). Every role that is not brought to a new template below keeps what
-- it opens today: it gets HR-only documents if it reads Documents, and Full identifiers if it reads
-- Statutory Details.
--
-- Which roles follow the template: a company-wide role with the template's name (and no team-only setting)
-- that holds nothing the old template did not give, and either holds all of it, or was never changed by a
-- person (no audit row a person wrote names it; the roles screen and the role routes write one on every
-- change, and the audit log is append-only). That second test is what brings along a role made from an older
-- version of the template, which an exact match would miss. A role someone changed is left as it is; an
-- audit row says so, and the roles screen shows how it differs from the template (roles.ts `template`).
--
-- A role that already is the new template counts as following it, so a second run changes nothing more. One
-- statement after the permission rows, so which roles follow is decided before anything is changed.
