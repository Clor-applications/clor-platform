template_size AS MATERIALIZED (
  SELECT "name", 'old' AS "which", count(*) AS "n" FROM old_template GROUP BY "name"
  UNION ALL
  SELECT "name", 'new', count(*) FROM new_template GROUP BY "name"
),
named AS MATERIALIZED (
  SELECT r."id", r."accountId", r."orgId", lower(r."name") AS "name", r."ownDocumentsOnly"
  FROM "Role" r
  WHERE lower(r."name") IN ('hr user', 'hr manager', 'viewer', 'auditor') AND r."branchId" IS NULL
),
-- Per named role: how many grants it holds, and how many of them each version of its template gives.
tally AS MATERIALIZED (
  SELECT n."id",
    count(p."id") AS "total",
    count(o."name") AS "in_old",
    count(w."name") AS "in_new"
  FROM named n
  LEFT JOIN "RolePermission" rp ON rp."roleId" = n."id" AND rp."allowed"
  LEFT JOIN "Permission" p ON p."id" = rp."permissionId"
  LEFT JOIN old_template o ON o."name" = n."name" AND o."module" = p."module" AND o."subModule" = p."subModule" AND o."action" = p."action"
  LEFT JOIN new_template w ON w."name" = n."name" AND w."module" = p."module" AND w."subModule" = p."subModule" AND w."action" = p."action"
  GROUP BY n."id"
),
touched AS MATERIALIZED (
  SELECT DISTINCT a."entityId" AS "id"
  FROM "AuditLog" a JOIN named n ON a."orgId" = n."orgId" AND a."entityId" = n."id"
  WHERE a."createdByUserId" <> 'system'
),
shape AS MATERIALIZED (
  SELECT n."id", n."accountId", n."orgId", n."name",
    NOT n."ownDocumentsOnly" AND t."total" = t."in_new" AND t."in_new" = (SELECT z."n" FROM template_size z WHERE z."name" = n."name" AND z."which" = 'new') AS "is_new",
    NOT n."ownDocumentsOnly" AND t."total" = t."in_old"
      AND (t."in_old" = (SELECT z."n" FROM template_size z WHERE z."name" = n."name" AND z."which" = 'old') OR n."id" NOT IN (SELECT "id" FROM touched)) AS "follows"
  FROM named n JOIN tally t ON t."id" = n."id"
),
-- Brought to the new template now; a role that already is the new template is left exactly so.
moving AS MATERIALIZED (
  SELECT "id", "accountId", "orgId", "name" FROM shape WHERE "follows" AND NOT "is_new"
),
settled AS MATERIALIZED (
  SELECT "id" FROM shape WHERE "follows" OR "is_new"
),
kept AS (
  INSERT INTO "RolePermission" ("id", "accountId", "orgId", "roleId", "permissionId", "allowed", "permLevel")
  SELECT gen_random_uuid()::text, r."accountId", r."orgId", r."id", np."id", true, 0
  FROM "Role" r
  JOIN "RolePermission" rp ON rp."roleId" = r."id" AND rp."allowed"
  JOIN "Permission" h ON h."id" = rp."permissionId" AND h."module" = 'PEOPLE' AND h."action" = 'VIEW' AND h."subModule" IN ('Documents', 'Statutory Details')
  JOIN "Permission" np ON np."module" = 'PEOPLE' AND np."action" = 'VIEW' AND np."subModule" = CASE h."subModule" WHEN 'Documents' THEN 'HR-only Documents' ELSE 'Full Identifiers' END
  WHERE NOT EXISTS (SELECT 1 FROM settled s WHERE s."id" = r."id")
  ON CONFLICT ("roleId", "permissionId") DO NOTHING
  RETURNING 1
),
dropped AS (
  DELETE FROM "RolePermission" rp
  USING moving s, "Permission" p
  WHERE rp."roleId" = s."id" AND p."id" = rp."permissionId"
    AND NOT EXISTS (SELECT 1 FROM new_template t WHERE t."name" = s."name" AND t."module" = p."module" AND t."subModule" = p."subModule" AND t."action" = p."action")
  RETURNING 1
),
added AS (
  INSERT INTO "RolePermission" ("id", "accountId", "orgId", "roleId", "permissionId", "allowed", "permLevel")
  SELECT gen_random_uuid()::text, s."accountId", s."orgId", s."id", p."id", true, 0
  FROM moving s
  JOIN new_template t ON t."name" = s."name"
  JOIN "Permission" p ON p."module" = t."module" AND p."subModule" = t."subModule" AND p."action" = t."action"
  ON CONFLICT ("roleId", "permissionId") DO UPDATE SET "allowed" = true WHERE NOT "RolePermission"."allowed"
  RETURNING 1
),
described AS (
  UPDATE "Role" r SET "description" = d."new_description"
  FROM moving s JOIN descriptions d ON d."name" = s."name"
  WHERE r."id" = s."id" AND r."description" IS NOT DISTINCT FROM d."old_description"
  RETURNING 1
),
noted AS (
  -- Said once per role, in the audit trail: brought to the new template, or left as someone changed it.
  INSERT INTO "AuditLog" ("id", "accountId", "orgId", "branchId", "entity", "entityId", "action", "message", "createdByUserId")
  SELECT gen_random_uuid()::text, n."accountId", n."orgId", '', 'Role', n."id",
    CASE WHEN s."id" IS NULL THEN 'TEMPLATE_LEFT' ELSE 'TEMPLATE_APPLIED' END,
    CASE WHEN s."id" IS NULL
      THEN 'The ' || CASE n."name" WHEN 'hr user' THEN 'HR User' WHEN 'hr manager' THEN 'HR Manager' ELSE initcap(n."name") END || ' template changed (8 Nov 2026). This role was changed here before, so it was left as it is; the roles screen shows how it differs.'
      ELSE 'The ' || CASE n."name" WHEN 'hr user' THEN 'HR User' WHEN 'hr manager' THEN 'HR Manager' ELSE initcap(n."name") END || ' template changed (8 Nov 2026); this role, unchanged here, now matches it.' END,
    'system'
  FROM named n LEFT JOIN moving s ON s."id" = n."id"
  WHERE n."id" NOT IN (SELECT "id" FROM settled WHERE "id" NOT IN (SELECT "id" FROM moving))
    AND NOT EXISTS (SELECT 1 FROM "AuditLog" a WHERE a."orgId" = n."orgId" AND a."entityId" = n."id" AND a."action" IN ('TEMPLATE_LEFT', 'TEMPLATE_APPLIED') AND a."message" LIKE '%(8 Nov 2026)%')
  RETURNING 1
)
