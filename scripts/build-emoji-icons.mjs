#!/usr/bin/env node
/* Writes packages/ui/src/components/ui/fluentEmoji.data.js: the SVG bodies of every Fluent Emoji
   (flat) named in navEmoji.js and emoji('…') calls, nothing else. Gradient and clip ids are
   prefixed with the emoji's name so two different emoji on one page cannot share an id.
   Run after adding an emoji: node scripts/build-emoji-icons.mjs */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/fluent-emoji-flat/icons.json');

const names = new Set();
const walk = (dir) => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'dist') continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(jsx?|tsx?)$/.test(e.name)) for (const m of readFileSync(p, 'utf8').matchAll(/\bemoji\('([a-z0-9-]+)'\)/g)) names.add(m[1]);
  }
};
walk('apps');
walk('packages');

const out = {};
for (const name of [...names].sort()) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`No Fluent Emoji flat icon named ${name}`);
  if ((icon.width || set.width) !== 32 || (icon.height || set.height) !== 32) throw new Error(`${name} is not 32 × 32`);
  const ids = [...icon.body.matchAll(/id="([^"]+)"/g)].map((m) => m[1]);
  let body = icon.body;
  for (const id of ids) body = body.replaceAll(`id="${id}"`, `id="fe-${name}-${id}"`).replaceAll(`url(#${id})`, `url(#fe-${name}-${id})`).replaceAll(`href="#${id}"`, `href="#fe-${name}-${id}"`);
  out[name] = body;
}

const file = `/* Generated by scripts/build-emoji-icons.mjs from @iconify-json/fluent-emoji-flat ${require('@iconify-json/fluent-emoji-flat/package.json').version}.
   Fluent Emoji © Microsoft, MIT licence. Do not edit by hand. */
export const FLUENT_EMOJI = ${JSON.stringify(out, null, 1)};
`;
writeFileSync('packages/ui/src/components/ui/fluentEmoji.data.js', file);
console.log(`${Object.keys(out).length} emoji written`);
